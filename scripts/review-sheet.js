#!/usr/bin/env node
/**
 * scripts/review-sheet.js
 * Write a printable review sheet of an edition's questions: every question
 * with its options, the answer and the note (source), grouped by category ›
 * subcategory, with a box to tick. For a reviewer who doesn't have the game.
 *
 *   node scripts/review-sheet.js prophets-stories
 *       → game_editions/prophets-stories/REVIEW.md
 *
 * Fix anything found in questions.csv (keep the id), then run
 * `npm run build:content <edition>`. Dev tooling only.
 */

const fs = require('node:fs');
const path = require('node:path');
const { listEditions, loadEdition } = require('./content.js');

const id = process.argv[2];
if (!id || !listEditions().includes(id)) {
  console.log(`Usage: node scripts/review-sheet.js <edition>\nEditions: ${listEditions().join(', ')}`);
  process.exit(1);
}
const ed = loadEdition(id);
const name = ed.config.GAME?.editionName ?? id;
const md = s => String(s ?? '').replace(/<[^>]*>/g, '').replace(/([*_`|])/g, '\\$1');

const groups = new Map();
for (const q of ed.questions) {
  const key = `${q.cat || 'Other'}\u0000${q.subcat || ''}`;
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(q);
}

const out = [
  `# ${name} — question review`,
  '',
  `${ed.questions.length} questions. For each one, check the question, the answer (✅) and the source. ` +
  'Write corrections next to it, quoting the **#number** — numbers never change.',
  '',
  '*Generated by `node scripts/review-sheet.js ' + id + '` from questions.csv.*',
];
let lastCat = null;
for (const [key, qs] of groups) {
  const [cat, sub] = key.split('\u0000');
  if (cat !== lastCat) { out.push('', `## ${md(cat)}`); lastCat = cat; }
  if (sub) out.push('', `### ${md(sub)}`);
  for (const q of qs) {
    const tags = [q.diff, q.topic].filter(Boolean).join(' · ');
    out.push('', `- [ ] **#${q.id}** ${md(q.q)}  \n  <sub>${md(tags)}</sub>`);
    if (q.opts?.length) {
      q.opts.forEach((o, i) => out.push(`    ${'ABCD'[i] === q.answer ? '✅' : '▫️'} ${md(o)}`));
    } else {
      out.push(`    ✅ ${md(q.answer)}`);
    }
    if (q.note) out.push(`    *Source:* ${md(q.note)}`);
  }
}
const file = path.join(ed.dir, 'REVIEW.md');
fs.writeFileSync(file, out.join('\n') + '\n');
console.log(`✓ ${path.relative(process.cwd(), file)} — ${ed.questions.length} questions`);
